#!/usr/bin/env python3
"""embed.py IN.png OUT.h NAME - write a PNG as a C byte array header."""
import sys
data = open(sys.argv[1], 'rb').read()
name = sys.argv[3]
with open(sys.argv[2], 'w') as f:
    f.write(f'// Generated by tools/embed.py from {sys.argv[1]} - do not edit.\n#pragma once\n')
    f.write(f'static const unsigned char {name}[] = {{\n')
    for i in range(0, len(data), 16):
        f.write('  ' + ', '.join(f'0x{b:02x}' for b in data[i:i+16]) + ',\n')
    f.write(f'}};\nstatic const int {name}_len = {len(data)};\n')
